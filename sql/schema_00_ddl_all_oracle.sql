CREATE TABLE pred_daily (
  target_date          DATE              NOT NULL,
  region_cd            VARCHAR2(24 CHAR) NOT NULL,
  run_id               NUMBER(19)        NOT NULL,
  is_current           NUMBER(1)    DEFAULT 1 NOT NULL,
  expected_count       NUMBER(10,6),
  occur_probability    NUMBER(7,6),
  occur_prob_raw       NUMBER(7,6),
  risk_grade           VARCHAR2(8 CHAR),
