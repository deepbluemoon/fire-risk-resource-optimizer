  confidence           VARCHAR2(8 CHAR)  DEFAULT '정상' NOT NULL,
  data_status          VARCHAR2(10 CHAR) DEFAULT '정상' NOT NULL,
  source_model_version VARCHAR2(40 CHAR),
  created_at           TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_pred_daily     PRIMARY KEY (target_date, region_cd, run_id),
  CONSTRAINT ck_pred_current   CHECK (is_current IN (0,1)),
  CONSTRAINT ck_pred_grade     CHECK (risk_grade IN ('낮음','보통','높음','매우높음')),
  CONSTRAINT ck_pred_conf      CHECK (confidence IN ('정상','대리지점','폴백')),
  CONSTRAINT ck_pred_status    CHECK (data_status IN ('정상','최신아님','데이터없음')),
  CONSTRAINT ck_pred_prob      CHECK (occur_probability BETWEEN 0 AND 1),
  CONSTRAINT ck_pred_spread    CHECK (spread_probability BETWEEN 0 AND 1),
  CONSTRAINT ck_pred_factor_js CHECK (top_factors IS JSON),
  CONSTRAINT ck_pred_nodata    CHECK (data_status <> '데이터없음'
