-- =============================================================================
-- schema_00_ddl_all_oracle.sql — 전체 구조 생성 DDL (Oracle 이식본)
--
--   원본        : schema_00_ddl_all.sql (MariaDB)
--   대상 DBMS   : Oracle Database 12c Release 1 (12.1.0.2) 이상
--   설계 근거   : docs/usecases/DB_00_데이터베이스구조설계_*.md
--   생성 대상   : 테이블 23개 + 인덱스 13개 + 주석
--
-- 실행 방법
--   sqlplus <user>/<password>@<tns> @schema_00_ddl_all_oracle.sql
--   자격증명은 이 파일에 쓰지 않는다(.env / FIRE_DB_* 환경변수 사용).
--
-- 선행 조건
--   1) DB 캐릭터셋이 AL32UTF8 이어야 한다. CHECK 제약과 기본값에 한글이 들어간다.
--        SELECT value FROM nls_database_parameters WHERE parameter='NLS_CHARACTERSET';
--   2) IDENTITY 컬럼은 12c 이상이다. 11g 이하는 파일 끝 부록 A(시퀀스+트리거)를 쓴다.
--   3) IS JSON 제약은 12.1.0.2 이상이다. 21c 이상이면 부록 B(네이티브 JSON)를 참고한다.
--
-- 원본과의 차이 (MariaDB → Oracle)
--   타입
--     VARCHAR(n)        → VARCHAR2(n CHAR)   문자 기준 길이. 한글이 바이트로 잘리지 않게 한다
--     TINYINT(1)        → NUMBER(1)          + CHECK IN (0,1)
--     TINYINT           → NUMBER(3)
--     SMALLINT          → NUMBER(5)
--     INT               → NUMBER(10)
--     BIGINT            → NUMBER(19)
--     DECIMAL(p,s)      → NUMBER(p,s)
--     DATETIME(3)       → TIMESTAMP(3)
--     DATETIME          → TIMESTAMP(0)
--     TEXT              → CLOB
--     JSON              → CLOB + CHECK (col IS JSON)
--     ENUM('a','b')     → VARCHAR2(n CHAR) + CHECK IN ('a','b')
--   구문
--     AUTO_INCREMENT            → GENERATED BY DEFAULT AS IDENTITY
--     DEFAULT CURRENT_TIMESTAMP → DEFAULT SYSTIMESTAMP
--     인라인 COMMENT            → COMMENT ON TABLE / COLUMN (문장 분리)
--     KEY ix_x (...)            → CREATE INDEX (문장 분리)
--     CHAR_LENGTH()             → LENGTH()
--     ENGINE=InnoDB CHARSET=... → 삭제
--     CREATE TABLE IF NOT EXISTS → CREATE TABLE (Oracle 23ai 미만은 미지원)
--                                  재실행하려면 파일 끝 부록 C 의 DROP 을 먼저 돌린다
--   컬럼명 변경 — 두 건뿐이며 이유가 다르다
--     ops_allocation_proposal.mode → alloc_mode
--         MODE 는 Oracle **예약어**다. "mode" 로 인용하면 애플리케이션 SQL 전부가
--         큰따옴표를 달아야 하므로 이름을 바꾸는 쪽이 낫다.
--     pred_cause_top3.`rank`       → rank_no
--         RANK 는 예약어는 아니나 분석함수명이라 혼동을 부른다. 원본도 백틱을 쓰고 있었다.
--     ※ 이식 시 애플리케이션 쿼리에서 이 두 컬럼명을 함께 바꿔야 한다.
--
-- 이식 시 주의 — Oracle DATE 는 시각을 포함한다
--   MariaDB DATE 는 날짜만 담지만 Oracle DATE 는 시·분·초를 함께 담는다.
--   target_date 는 pred_daily · ref_actual_* 의 **기본키 구성 컬럼**이므로,
--   시각이 섞여 들어오면 같은 날짜가 서로 다른 키가 되어 하루 251행 원칙(SC-006)이
--   조용히 깨진다. 적재 코드는 반드시 TRUNC 로 자정 기준으로 맞춘다.
--       INSERT ... VALUES (TRUNC(:target_date), ...)
--   조회도 등가비교가 안전하다:  WHERE target_date = TRUNC(:d)
--   원한다면 다음 제약을 추가해 강제할 수 있다(선택):
--       ALTER TABLE pred_daily ADD CONSTRAINT ck_pred_date_trunc
--             CHECK (target_date = TRUNC(target_date));
--
-- 실행 순서 (파일 내부가 이미 이 순서다)
--   1) ops_model_registry · ops_batch_run   2) ref_region_profile
--   3) ref_*  4) pred_*  5) ops_*  6) 신규 4
-- =============================================================================

